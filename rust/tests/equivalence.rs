#![allow(clippy::excessive_precision, clippy::unreadable_literal)]

use tennessee_eastman::{default_delta_t, TennesseeEastmanProcess};

fn rel(a: f64, b: f64) -> f64 {
    let den = b.abs().max(1e-12);
    (a - b).abs() / den
}

fn max_rel(got: &[f64], gold: &[f64]) -> (f64, usize) {
    got.iter()
        .zip(gold)
        .enumerate()
        .map(|(i, (g, h))| (rel(*g, *h), i))
        .max_by(|a, b| a.0.partial_cmp(&b.0).unwrap())
        .unwrap()
}

fn max_abs(got: &[f64], gold: &[f64]) -> (f64, usize) {
    got.iter()
        .zip(gold)
        .enumerate()
        .map(|(i, (g, h))| ((g - h).abs(), i))
        .max_by(|a, b| a.0.partial_cmp(&b.0).unwrap())
        .unwrap()
}

fn report(got: &[f64], gold: &[f64], name: &str) -> String {
    got.iter()
        .zip(gold)
        .enumerate()
        .map(|(i, (g, h))| {
            format!(
                "{name}({:2}) got={:.8e} gold={:.8e} abs={:.3e} rel={:.3e}",
                i + 1,
                g,
                h,
                (g - h).abs(),
                rel(*g, *h)
            )
        })
        .collect::<Vec<_>>()
        .join("\n")
}

#[test]
fn default_delta_t_matches_fortran_real_divide() {
    let dt = default_delta_t();
    let gold = 0.2777777845039964e-3;
    assert!(
        (dt - gold).abs() < 1e-18,
        "DELTAT={dt:.16e} gold={gold:.16e}"
    );
}

#[test]
fn teinit_yy_matches_gfortran() {
    let mut p = TennesseeEastmanProcess::new();
    p.teinit();
    let gold = gold_yy();
    let (err, idx) = max_rel(&p.yy, &gold);
    assert!(
        err < 1e-14,
        "YY[{}] relative error {err:.3e}: got={} gold={}",
        idx + 1,
        p.yy[idx],
        gold[idx]
    );
}

#[test]
fn teinit_xmeas_matches_gfortran() {
    let mut p = TennesseeEastmanProcess::new();
    p.teinit();
    let gold = gold_xmeas();
    let (err, idx) = max_rel(p.xmeas(), &gold);
    assert!(
        err < 1e-7,
        "XMEAS[{}] relative error {err:.3e}: got={} gold={}",
        idx + 1,
        p.xmeas()[idx],
        gold[idx]
    );
}

#[test]
fn teinit_yp_matches_gfortran() {
    let mut p = TennesseeEastmanProcess::new();
    p.teinit();
    let gold = gold_yp();
    let (err, idx) = max_abs(&p.yp, &gold);
    assert!(
        err < 1e-12,
        "YP[{}] abs error {err:.3e}: got={} gold={}\n{}",
        idx + 1,
        p.yp[idx],
        gold[idx],
        report(&p.yp, &gold, "YP")
    );
}

#[test]
fn one_euler_step_then_tefunc_matches_gfortran() {
    let mut p = TennesseeEastmanProcess::new();
    p.teinit();
    assert_eq!(p.g, 4_651_207_995.0);
    p.integrate(default_delta_t());
    assert_eq!(p.g, 4_651_207_995.0, "INTGTR at TIME=0 must not draw noise");
    assert!((p.time - default_delta_t()).abs() < 1e-18);
    let gold_yy3 = gold_yy_after_step();
    let (err, idx) = max_rel(&p.yy, &gold_yy3);
    assert!(
        err < 1e-8,
        "YY[{}] after Euler relative error {err:.3e}: got={} gold={}",
        idx + 1,
        p.yy[idx],
        gold_yy3[idx]
    );

    p.tefunc();
    assert!(p.g != 4_651_207_995.0, "TESUB7 must advance after t>0");
    let gold_g = 0.3411419128000000e10;
    let gerr = (p.g - gold_g).abs() / gold_g;
    assert!(
        gerr < 1e-12,
        "G after tefunc at dt: {} gold {}",
        p.g,
        gold_g
    );

    let gold_xmeas3 = gold_xmeas_after_step();
    let (err, idx) = max_rel(p.xmeas(), &gold_xmeas3);
    assert!(
        err < 5e-5,
        "XMEAS[{}] after 1 s relative error {err:.3e}: got={} gold={}",
        idx + 1,
        p.xmeas()[idx],
        gold_xmeas3[idx]
    );
    assert!(!p.is_shutdown());
}

#[test]
fn observation_layout_is_41_meas_plus_11_mv() {
    let mut p = TennesseeEastmanProcess::new();
    p.teinit();
    let obs = p.observation();
    assert_eq!(obs.len(), 52);
    assert_eq!(obs[0], p.xmeas()[0]);
    assert_eq!(obs[40], p.xmeas()[40]);
    assert_eq!(obs[41], p.xmv()[0]);
    assert_eq!(obs[51], p.xmv()[10]);
}

#[test]
fn closed_loop_short_run_stays_near_base_case() {
    use tennessee_eastman::{ClosedLoopConfig, PlantWideController};
    let mut p = TennesseeEastmanProcess::new();
    p.teinit();
    let cfg = ClosedLoopConfig {
        npts: 360,
        sspts: 10_000,
        delta_t: default_delta_t(),
        idv_after_ss: vec![],
    };
    let mut ctrl = PlantWideController::new(cfg.delta_t);
    PlantWideController::apply_base_xmv(&mut p);
    for i in 1..=cfg.npts {
        ctrl.step(&mut p, i);
        p.integrate(cfg.delta_t);
        ctrl.constrain_hand(&mut p);
        assert!(!p.is_shutdown(), "shutdown at step {i}");
    }
    let t = p.xmeas()[8];
    assert!(
        (t - 120.4).abs() < 5.0,
        "reactor temperature drifted too far: {t}"
    );
}

